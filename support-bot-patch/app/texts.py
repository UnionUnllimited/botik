# ============================================================
#  Автоподстановка значений из .env во все тексты выше.
#  Проходим по всем строковым константам модуля, в которых есть
#  плейсхолдеры {MAIN_BOT}/{COMMUNITY_CHAT_URL}/{NEWS_CHANNEL_URL},
#  и заменяем их на реальные значения. Делается один раз при импорте.
# ============================================================

def _apply_links() -> None:
    g = globals()
    for _name, _value in list(g.items()):
        if _name.startswith("_") or not isinstance(_value, str):
            continue
        if "{" not in _value:
            continue
        # Только если в строке есть наши плейсхолдеры
        if any(("{" + k + "}") in _value for k in _LINKS):
            try:
                g[_name] = _value.format(**_LINKS)
            except (KeyError, IndexError, ValueError):
                # Если в тексте оказались чужие {фигурные скобки} — пропускаем,
                # чтобы не сломать загрузку модуля.
                pass


_apply_links()

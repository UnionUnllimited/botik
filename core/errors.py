"""Как называть ошибку в журнале.

Часть исключений не имеет текста вовсе: у `httpx.ReadError` и его родни
`str()` возвращает пустую строку. Запись `{"error": ""}` сообщает, что
не вышло, и ничего — о том, почему. Ровно такая запись 22 сентября 2026
стоила лишнего часа: дашборд frps перестал отвечать через мост, а в журнале
была пустая строка вместо «соединение оборвано».

Имя класса есть всегда, и его одного хватает, чтобы отличить обрыв
от отказа и таймаут от неверного пароля.
"""

from __future__ import annotations


def describe(exc: BaseException) -> str:
    """Текст ошибки для журнала: всегда непустой."""
    text = str(exc).strip()
    name = type(exc).__name__
    return f"{name}: {text}" if text else name

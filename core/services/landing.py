"""Постоянная инструкция: она нужна не в первый день, а потом.

Отдельно от шагов подключения намеренно. Те читают один раз и забывают,
а сюда возвращаются с вопросами «где пароль от Wi-Fi», «как продлить»
и «пропал интернет» — и искать их среди шагов распаковки неудобно."""


def money(value: Decimal | None) -> str:
    """«6 900 ₽» — без копеек, если их нет: витрина не бухгалтерия."""
    if value is None:
        return ""
    quantized = Decimal(value).quantize(Decimal("0.01"))
    whole = int(quantized)
    tail = quantized - whole
    grouped = f"{whole:,}".replace(",", " ")
    if tail:
        return f"{grouped},{int(tail * 100):02d} ₽"
    return f"{grouped} ₽"


def period_text(plan: Plan) -> str:
    """«12 мес. +30 дн.» — тот же способ назвать срок, что и в боте."""
    parts = []
    if plan.months:
        parts.append(f"{plan.months} мес.")
    if plan.extra_days:
        parts.append(f"+{plan.extra_days} дн.")
    return " ".join(parts) or plan.title


def absolute(path: str) -> str:
    """Путь из настройки — в адрес, по которому картинку отдадут снаружи."""
    raw = (path or "").strip()
    if not raw or raw.startswith("http"):
        return raw
    return f"{settings.api.public_base_url.rstrip('/')}{raw}"


def photo_url(product: Product) -> str:
    """Абсолютный адрес картинки: витрину открывают и по другому домену."""
    return absolute(product.photo_url or "")


def bot_link(payload: str = "") -> str:
    """Ссылка в бота, при необходимости — сразу на нужный экран.

    Пустой `APP_BOT_USERNAME` значит, что ссылку собрать не из чего:
    вместо неработающей кнопки витрина покажет подсказку про Telegram.
    """
    username = settings.app.bot_username.strip().lstrip("@")
    if not username:
        return ""
    if payload:
        return f"https://t.me/{username}?start={payload}"
    return f"https://t.me/{username}"


DEFAULT_LOGO_URL = "/static/logo.svg"
DEFAULT_FAVICON_URL = "/static/favicon.svg"
"""Свои знаки в статике: они есть всегда, даже когда оператор ничего не грузил.

Их два, и это не дубль. В шапке нужна одна буква: рядом с названием, высотой
в строку, мелкие детали слипаются. Во вкладке — знак целиком, там он квадратный
и узнаётся именно по картинке.
"""


async def hero_image(session: AsyncSession, products: list[dict[str, Any]]) -> str:
    """Картинка первого экрана.

    Оператор ставит ту же, что висит баннером над главным меню бота: клиент
    приходит с витрины в чат и видит то же изображение — переход не рвётся.
    Ничего не поставили — берём фото первой модели: пустое место на первом
    экране хуже, чем фото товара.
    """
    configured = (await settings_service.get_str(session, "landing.hero_image_url")).strip()
    if configured:
        return absolute(configured)
    return products[0]["photo_url"] if products else ""


async def logo_url(session: AsyncSession, fallback: str = DEFAULT_LOGO_URL) -> str:
    """Логотип в шапке витрины.

    `fallback` передаёт маршрут: он видит, какие файлы реально лежат в статике,
    и подставляет положенный туда `logo.png`, если он есть.
    """
    configured = (await settings_service.get_str(session, "landing.logo_url")).strip()
    return configured or fallback


async def favicon_url(session: AsyncSession, fallback: str = DEFAULT_FAVICON_URL) -> str:
    """Значок вкладки браузера."""
    configured = (await settings_service.get_str(session, "landing.favicon_url")).strip()
    return configured or fallback


def product_card(product: Product) -> dict[str, Any]:
    """Карточка для витрины.

    `model_code` наружу не идёт: клиенту показывается название товара,
    а не модель железа — то же решение, что и на экране «Мой роутер».
    """
    return {
        "id": product.id,
        "slug": product.slug,
        "title": product.title,
        "subtitle": product.subtitle or "",
        "description": product.description or "",
        "price": money(product.price),
        "old_price": money(product.old_price) if product.old_price else "",
        # Выгода рублями, а не процентами: на цене в тысячи «−2 601 ₽»
        # читается весомее, чем «−22%», и не требует считать в уме.
        # Считаем здесь, а не в вёрстке: там цены уже строки с пробелами
        # и знаком рубля, и вычитать пришлось бы разбором текста.
        "saving": (
            money(product.old_price - product.price)
            if product.old_price and product.old_price > product.price
            else ""
        ),
        "in_stock": product.in_stock,
        "preorder": product.stock <= 0 and product.allow_preorder,
        "specs": list((product.specs or {}).items()),
        "photo_url": photo_url(product),
        "buy_url": bot_link(f"buy_{product.id}"),
    }


TRAFFIC_WORDS = ("gb", "гб", "гигабайт", "трафик", "будет добавлено")
"""Следы подписки для телефона в описаниях тарифов.

Тарифы заводились под неё, и в описании осталось «Будет добавлено: 15 GB».
К роутеру это не относится: гигабайты мы не считаем и не продаём, за роутером
стоит квартира. Показать такую строку на витрине — пообещать то, чего нет."""


def plan_description(plan: Plan) -> str:
    """Описание тарифа без строк про гигабайты."""
    lines = [
        line.strip()
        for line in (plan.description or "").splitlines()
        if line.strip() and not any(word in line.lower() for word in TRAFFIC_WORDS)
    ]
    return " ".join(lines)


def plan_card(plan: Plan) -> dict[str, Any]:
    return {
        "id": plan.id,
        "title": plan.title,
        "period": period_text(plan),
        "price": money(plan.price),
        "per_month": money(plan.price_per_month) if plan.months > 1 else "",
        "description": plan_description(plan),
    }


async def page_content(
    session: AsyncSession,
    *,
    logo_fallback: str = DEFAULT_LOGO_URL,
    favicon_fallback: str = DEFAULT_FAVICON_URL,
) -> dict[str, Any]:
    """Всё, что нужно шаблону витрины, одним запросом на раздел."""
    products = list(
        await session.scalars(
            select(Product)
            .where(Product.is_active.is_(True))
            .order_by(Product.sort_order, Product.id)
        )
    )
    plans = list(
        await session.scalars(
            select(Plan).where(Plan.is_active.is_(True)).order_by(Plan.sort_order, Plan.months)
        )
    )

    hero_title = await settings_service.get_str(session, "landing.hero_title")
    hero_subtitle = await settings_service.get_str(session, "landing.hero_subtitle")
    support = await settings_service.get_str(session, "support.contact")

    cards = [product_card(product) for product in products]
    return {
        "brand": settings.app.brand,
        "hero_image": await hero_image(session, cards),
        "logo_url": await logo_url(session, logo_fallback),
        "favicon_url": await favicon_url(session, favicon_fallback),
        "hero_title": hero_title or settings_service.DEFAULTS["landing.hero_title"],
        "hero_subtitle": hero_subtitle or settings_service.DEFAULTS["landing.hero_subtitle"],
        "products": cards,
        "plans": [plan_card(plan) for plan in plans],
        "steps": STEPS,
        "features": FEATURES,
        "value": VALUE,
        "marquee": MARQUEE,
        "home_points": HOME_POINTS,
        "comparison": COMPARISON,
        "faq": FAQ,
        "bot_url": bot_link(),
        "support_contact": support,
    }


async def is_enabled(session: AsyncSession) -> bool:
    return await settings_service.get_bool(session, "landing.enabled")
